#!/usr/bin/env python3
"""Generate db/import/mob_db.yml: Id + Level*10 overrides for every mob.

Compensates for the effective-level change in status_calc_misc (HIT/FLEE
now use level/10), which would otherwise crush mob HIT/FLEE contribution
tenfold relative to players.
"""
import re

SRC = "db/pre-re/mob_db.yml"
DST = "db/import/mob_db.yml"

with open(SRC, encoding="utf-8") as f:
    content = f.read()

# Only look at the Body section (after "Body:")
body_start = content.index("\nBody:")
body = content[body_start:]

entries = re.findall(r"^  - Id:\s*(\d+)[\s\S]*?^    Level:\s*(\d+)", body, re.M)

if len(entries) < 1000:
    raise SystemExit(f"Expected ~1004 entries, parsed {len(entries)} -- aborting, check regex")

header = """# This file is a part of rAthena.
#   Copyright(C) 2021 rAthena Development Team
#   https://rathena.org - https://github.com/rathena
#
# This program is free software: you can redistribute it and/or modify
# it under the terms of the GNU General Public License as published by
# the Free Software Foundation, either version 3 of the License, or
# (at your option) any later version.
#
# This program is distributed in the hope that it will be useful,
# but WITHOUT ANY WARRANTY; without even the implied warranty of
# MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the
# GNU General Public License for more details.
#
# You should have received a copy of the GNU General Public License
# along with this program. If not, see <http://www.gnu.org/licenses/>.
#
###########################################################################
# Monster Database - Aethera overrides
###########################################################################
#
# Every monster's Level is multiplied by 10 here. status_calc_misc now
# divides level by 10 (effective level) for HIT/FLEE, for both players
# and monsters, to keep DEX/AGI meaningful at level 999 instead of raw
# level swamping the formula. This file compensates so monsters land
# back on their original effective level after that division.
# Generated by gen_mob_level_scale.py from db/pre-re/mob_db.yml -- do
# not hand-edit scaled values, regenerate instead if base levels change.
###########################################################################

Header:
  Type: MOB_DB
  Version: 5

Body:
"""

lines = [header]
for mob_id, level in entries:
    lines.append(f"  - Id: {mob_id}\n    Level: {int(level) * 10}\n")

with open(DST, "w", encoding="utf-8") as f:
    f.write("".join(lines))

print(f"Wrote {len(entries)} entries to {DST}")
